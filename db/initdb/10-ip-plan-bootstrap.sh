#!/usr/bin/env bash
# Init-скрипт официального образа postgres: выполняется ТОЛЬКО на пустом
# томе pg_data, при первом старте. Сам bootstrap.sh сюда не монтируется
# напрямую: неисполняемые *.sh образ не запускает, а подключает через
# `source` в свой процесс — тогда `set -u` и `exit` из bootstrap.sh
# действовали бы на сам entrypoint. Отдельный процесс bash от этого изолирует,
# а ненулевой код возврата всё равно прерывает инициализацию (entrypoint
# работает под set -e).
bash /opt/ip_plan_db/bootstrap.sh
